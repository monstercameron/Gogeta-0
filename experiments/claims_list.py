"""Generate experiments/claims-status.md: one line per claim with its LATEST status, from experiments/claims.md.

claims.md is an append-only ledger: a claim's first row can be stale (e.g. C15 listed UNVERIFIED in the
main table, VERIFIED in the later K1-K6 verdict section). This script reads every table row that names a
claim ID, in file order, and keeps the last status seen for each ID, plus where each status came from.
Stdlib only. Usage: python experiments/claims_list.py [--check]   (--check: exit 1 if claims-status.md is stale)
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC, OUT = ROOT / "experiments/claims.md", ROOT / "experiments/claims-status.md"
STATUSES = ["VERIFIED", "PARTIAL", "REFUTED", "WRONG FOR OUR CODE", "INCONCLUSIVE", "UNVERIFIED"]
ID_RE = re.compile(r"^\|\s*(?:\*\*)?(C\d+)\b(?:\s*\(new\))?(?:\*\*)?\s*([^|]*)\|(.*)$")
ST_RE = re.compile(r"`(VERIFIED|PARTIAL|REFUTED|WRONG FOR OUR CODE|INCONCLUSIVE|UNVERIFIED)([^`]*)`")


def clean(s, n=None):
    s = re.sub(r"[`*]", "", s).strip()
    return (s[: n - 1] + "…") if n and len(s) > n else s


def parse():
    claims, section = {}, ""
    for i, line in enumerate(SRC.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        m = ID_RE.match(line)
        if not m:
            continue
        cid, inline, rest = m.group(1), m.group(2).strip(), m.group(3)
        cells = [c.strip() for c in rest.split("|")]
        st = ST_RE.search(rest)
        if not st:
            continue  # e.g. the "proposed checks" table, which maps checks to claims
        text = inline or (cells[0] if cells else "")
        evidence = cells[-2] if len(cells) >= 2 and cells[-1] == "" else (cells[-1] if cells else "")
        c = claims.setdefault(cid, {"id": cid, "text": clean(text), "history": []})
        if inline and not c["text"]:
            c["text"] = clean(inline)
        c["history"].append({"status": st.group(1), "qual": st.group(2).strip(" ()"), "section": section,
                             "line": i, "evidence": clean(evidence, 220)})
    return claims


def render(claims):
    key = lambda c: int(c["id"][1:])
    rows = sorted(claims.values(), key=key)
    by = {s: [c for c in rows if c["history"][-1]["status"] == s] for s in STATUSES}
    out = ["# Claims: current status", "",
           "Generated by `python experiments/claims_list.py` from the ledger `experiments/claims.md` (append-only; "
           "this view keeps each claim's **latest** status). Don't edit by hand.", "",
           "| Status | Count |", "|---|---|"]
    out += [f"| {s} | {len(by[s])} |" for s in STATUSES if by[s]] + [f"| **Total** | {len(rows)} |", ""]
    for s in STATUSES:
        if not by[s]:
            continue
        out += [f"## {s} ({len(by[s])})", "", "| ID | Claim | Latest evidence | Ledger |", "|---|---|---|---|"]
        for c in by[s]:
            h = c["history"][-1]
            qual = f" ({h['qual']})" if h["qual"] else ""
            changed = " ⟵ was " + c["history"][0]["status"] if c["history"][0]["status"] != h["status"] else ""
            ev = h["evidence"].replace("|", "/")
            out.append(f"| {c['id']} | {c['text'].replace('|', '/')}{qual}{changed} | {ev} | "
                       f"[L{h['line']}](claims.md#L{h['line']}) |")
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    # Guard: on a case-insensitive filesystem (Windows) a name like CLAIMS.md IS claims.md. Writing the
    # generated list over the ledger destroyed it once (2026-11-22, caught before commit). Never again.
    if OUT.exists() and OUT.samefile(SRC) or str(OUT).lower() == str(SRC).lower():
        sys.exit(f"refusing: output {OUT} is the ledger itself")
    text = render(parse())
    if not text.count("\n| C"):
        sys.exit("refusing: parsed 0 claims from the ledger (is experiments/claims.md intact?)")
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
