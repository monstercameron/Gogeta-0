"""Build the site: docs/data/site-data.js (from DEVLOG.md + experiments/experiments.json), plus the
generated pages docs/experiments/E<n>.html (from experiments/writeups/) and docs/learn.html
(from site-src/learn.md). See tools/site_pages.py.

Usage:  python tools/build_site_data.py
Run it before cutting a version, so the GitHub Pages site matches the devlog.
Output is a JS file (not JSON) so the site also works when opened from disk.
"""
import datetime, html, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEVLOG = ROOT / "DEVLOG.md"
EXPERIMENTS = ROOT / "experiments" / "experiments.json"
OUT = ROOT / "docs" / "data" / "site-data.js"


def inline(text):
    """Tiny inline markdown: code, bold, italic, links. Input is HTML-escaped first."""
    t = html.escape(text, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![*\w])\*([^*]+)\*(?![*\w])", r"<em>\1</em>", t)
    t = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', t)
    return t


def md_block(lines):
    """Paragraphs + one level of '- ' lists. Lines starting with ** open a new paragraph."""
    out, para, items = [], [], []

    def flush():
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()
        if items:
            out.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>")
            items.clear()

    for raw in lines:
        line = raw.rstrip()
        s = line.strip()
        if not s:
            flush()
        elif re.match(r"^[-*] ", s):
            if para:
                flush()
            items.append(s[2:])
        elif items and line.startswith("  "):
            items[-1] += " " + s
        else:
            if items or s.startswith("**"):
                flush()
            para.append(s)
    flush()
    return "".join(out)


def parse_devlog():
    text = DEVLOG.read_text(encoding="utf-8")
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    entries = []
    for block in re.split(r"^## (?=v\d+\.\d+\.\d+)", text, flags=re.M)[1:]:
        lines = block.strip("\n").split("\n")
        m = re.match(r"(v\d+\.\d+\.\d+)\s*[:\-–—]\s*(.*)", lines[0])
        version, title = (m.group(1), m.group(2).strip()) if m else (lines[0], "")
        body = [l for l in lines[1:] if l.strip() != "---"]
        date = ""
        for i, l in enumerate(body):
            dm = re.fullmatch(r"\s*\*(\d{4}-\d{2}-\d{2})\*\s*", l)
            if dm:
                date = dm.group(1)
                body = body[:i] + body[i + 1:]
                break
        entries.append({"version": version, "title": title, "date": date, "html": md_block(body)})
    return entries


def main():
    data = {
        "generated": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "devlog": parse_devlog(),
        "experiments": json.loads(EXPERIMENTS.read_text(encoding="utf-8")),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    js = "// Generated by tools/build_site_data.py: do not edit by hand.\nwindow.SITE_DATA = " \
         + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"
    OUT.write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['devlog'])} versions, "
          f"{len(data['experiments'])} experiments")

    # Static pages: one per experiment (from experiments/writeups/) + the newcomer primer.
    import sys
    sys.path.insert(0, str(ROOT / "tools"))
    from site_pages import build_pages

    version = data["devlog"][0]["version"] if data["devlog"] else "v0"
    pages = build_pages(data["experiments"], version)
    print(f"wrote {len(pages)} pages: {', '.join(pathlib.Path(p).name for p in pages)}")


if __name__ == "__main__":
    main()
