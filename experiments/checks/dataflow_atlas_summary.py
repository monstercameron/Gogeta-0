"""Summarise results/dataflow_atlas.json (SQ439) into results/dataflow_atlas_summary.md: means over seeds per arm, per slice.
    python experiments/checks/dataflow_atlas_summary.py
"""
import json
import os
import statistics as st
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
d = json.load(open(os.path.join(RES, "dataflow_atlas.json")))
runs = d["runs"]
by_arm = defaultdict(list)
for k, v in runs.items():
    by_arm[k.rsplit("_s", 1)[0]].append(v)
ARMS = [a for a in ("A2s", "A2f", "E27", "E24", "E20") if a in by_arm]
SL = ("in_corpus", "out_of_corpus")
L = []


def m(xs):
    xs = [x for x in xs if x is not None]
    return st.mean(xs) if xs else float("nan")


def f(x, p=3):
    return "-" if x != x else f"{x:.{p}f}"


L.append("# SQ439 data-flow atlas: summary (means over seeds 2-4)\n")
L.append(f"{d['windows_per_slice']} windows x {d['T']} tokens per slice; CPU fp32; generated by `dataflow_atlas_summary.py` "
         "from `dataflow_atlas.json`. Logit-lens CE of intermediate states is a lens (those states are never trained to be "
         "decoded), not a probe.\n")

# 1. residual stream at boundaries
for sl in SL:
    L.append(f"\n## Residual stream at each boundary ({sl})\n")
    L.append("| arm | boundary | RMS | eff. rank | anisotropy | crest | lens CE (nats) |")
    L.append("|---|---|---|---|---|---|---|")
    for a in ARMS:
        names = list(by_arm[a][0][sl]["states"].keys())
        for n in names:
            vals = [r[sl]["states"][n] for r in by_arm[a]]
            L.append(f"| {a} | {n} | {f(m([v['rms'] for v in vals]),2)} | {f(m([v['eff_rank'] for v in vals]),1)} | "
                     f"{f(m([v['anisotropy'] for v in vals]))} | {f(m([v['crest'] for v in vals]),1)} | {f(m([v['lens_ce'] for v in vals]))} |")

# 2. block writes
L.append("\n## Block writes: ||delta|| / ||x|| and cos(delta, x) (in_corpus)\n")
L.append("| arm | block | kind | mixer rel | mixer cos | MLP rel | MLP cos |")
L.append("|---|---|---|---|---|---|---|")
for a in ARMS:
    for n in by_arm[a][0]["in_corpus"]["blocks"]:
        vals = [r["in_corpus"]["blocks"][n] for r in by_arm[a]]
        L.append(f"| {a} | {n} | {vals[0]['kind']} | {f(m([v['mix_rel'] for v in vals]))} | {f(m([v['mix_cos'] for v in vals]))} | "
                 f"{f(m([v['mlp_rel'] for v in vals]))} | {f(m([v['mlp_cos'] for v in vals]))} |")

# 3. loop
L.append("\n## Loop core: injection, pass change, pass-to-pass\n")
for sl in SL:
    for a in ARMS:
        lp = [r[sl]["loop"] for r in by_arm[a]]
        if not lp[0]:
            continue
        keys = list(lp[0].keys())
        parts = []
        for k in keys:
            sub = lp[0][k]
            for kk in sub:
                parts.append(f"{k}.{kk} {f(m([x[k][kk] for x in lp]))}")
        L.append(f"- **{a} ({sl}):** " + "; ".join(parts))

# 4. ternary error per projection type (in corpus and ooc)
for sl in SL:
    L.append(f"\n## Ternary output error by projection ({sl})\n")
    L.append("| arm | layer | total rel err | weight-only | act-only | input crest |")
    L.append("|---|---|---|---|---|---|")
    for a in ARMS:
        mods = by_arm[a][0][sl]["modules"].get("bitlinear", {})
        for n in mods:
            vals = [r[sl]["modules"]["bitlinear"][n] for r in by_arm[a]]
            L.append(f"| {a} | {n} | {f(m([v['err_total'] for v in vals]))} | {f(m([v['err_weight'] for v in vals]))} | "
                     f"{f(m([v['err_act'] for v in vals]))} | {f(m([v['in_crest'] for v in vals]),1)} |")

# 5. GDN and attention
L.append("\n## GDN heads: median decay horizon (tokens) and mean beta (in_corpus)\n")
for a in ARMS:
    mods = by_arm[a][0]["in_corpus"]["modules"].get("gdn", {})
    for n in mods:
        hz = [sum(c) / len(c) for c in zip(*[r["in_corpus"]["modules"]["gdn"][n]["horizon_med"] for r in by_arm[a]])]
        be = [sum(c) / len(c) for c in zip(*[r["in_corpus"]["modules"]["gdn"][n]["beta_mean"] for r in by_arm[a]])]
        L.append(f"- {a} {n}: horizon " + ", ".join(f"{x:.1f}" for x in hz) + " | beta " + ", ".join(f"{x:.2f}" for x in be))
L.append("\n## Attention heads: entropy (nats) and mean distance (tokens) (in_corpus)\n")
for a in ARMS:
    mods = by_arm[a][0]["in_corpus"]["modules"].get("attn", {})
    for n in mods:
        en = [sum(c) / len(c) for c in zip(*[r["in_corpus"]["modules"]["attn"][n]["entropy"] for r in by_arm[a]])]
        md = [sum(c) / len(c) for c in zip(*[r["in_corpus"]["modules"]["attn"][n]["mean_dist"] for r in by_arm[a]])]
        w = by_arm[a][0]["in_corpus"]["modules"]["attn"][n]["window"]
        L.append(f"- {a} {n} (window {w}): entropy " + ", ".join(f"{x:.2f}" for x in en) + " | dist " + ", ".join(f"{x:.0f}" for x in md))

open(os.path.join(RES, "dataflow_atlas_summary.md"), "w", newline="\n", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
