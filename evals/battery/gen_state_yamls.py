"""Writes the 18 frozen state-tracking task YAMLs into evals/tasks/battery/. Re-run only to rebuild (idempotent)."""
import pathlib
from evals.battery.state_track import GRID, N_PER_CELL

OUT = pathlib.Path(__file__).resolve().parents[1] / "tasks" / "battery"
T = """# Battery v1 state-tracking probe cell: mode={mode}, k={k} updates, {d} distractor lines. Generated by
# evals/battery/gen_state_yamls.py; do not hand-edit. 4-way multiple choice (chance 25%).
task: gogeta_state_{mode}_k{k}_d{d}
tag: [gogeta_battery, gogeta_battery_state]
custom_dataset: !function evals.tasks.battery.state_track.load_state_track
dataset_kwargs:
  mode: {mode}
  k: {k}
  distance: {d}
  n: {n}
  seed: 0
test_split: test
output_type: multiple_choice
doc_to_text: !function evals.tasks.battery.state_track.doc_prompt
doc_to_choice: !function evals.tasks.battery.state_track.doc_choices
doc_to_target: !function evals.tasks.battery.state_track.doc_gold
target_delimiter: ""
metric_list:
  - {{metric: acc, aggregation: mean, higher_is_better: true}}
metadata:
  version: 1.0
"""
for mode, cells in GRID.items():
    for k, d in cells:
        (OUT / f"gogeta_state_{mode}_k{k}_d{d}.yaml").write_text(T.format(mode=mode, k=k, d=d, n=N_PER_CELL))
print("wrote", sum(len(c) for c in GRID.values()), "yamls to", OUT)
