"""Build experiments/INDEX.md: the lookup table of every experiment, check and side quest.

    python tools/build_experiment_index.py      (also run by tools/build_site_data.py)

Sources (never hand-edit INDEX.md, it is generated):
  experiments/experiments.json         registry (E<n>): title, status, question, config
  experiments/cards/<ID>.md            per-experiment documentation card (front matter: id, type, title,
                                       status, headline, reuse). Cards win over the registry for headline/reuse.
  experiments/checks/results/*.json    check / side-quest results (verdicts)
  experiments/side-quests.md           side-quest log (status column)
"""
from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXP = ROOT / "experiments"
CARDS = EXP / "cards"
OUT = EXP / "INDEX.md"


def front_matter(path: pathlib.Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\s*\n(.*?)\n---", text, flags=re.S)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            k, sep, v = line.partition(":")
            if sep and k.strip():
                meta[k.strip()] = v.split("  #")[0].strip()
    return meta


def cell(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ").strip()


def short(s, n=140) -> str:
    s = cell(s)
    return s if len(s) <= n else s[: n - 1] + "…"


def load_check_results() -> dict:
    out = {}
    for p in sorted((EXP / "checks" / "results").glob("*.json")):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        cid = str(d.get("check") or p.stem)
        verdicts = d.get("verdicts", {})
        main = [f"{k}: {v}" for k, v in verdicts.items()
                if isinstance(v, str) and not k.endswith("_pass") and k not in ("pass",)]
        out[cid.upper()] = {"file": p.relative_to(ROOT).as_posix(), "verdict": "; ".join(main),
                            "ran_at": str(d.get("ran_at", ""))[:16], "claims": d.get("claims", [])}
    return out


def load_side_quests() -> dict:
    sq = {}
    path = EXP / "side-quests.md"
    if not path.exists():
        return sq
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(SQ\d+)\s*\|(.*)", line)
        if m:
            cols = [c.strip() for c in m.group(2).split("|")]
            status = next((c.strip("` ") for c in cols if c.strip("` ") in
                           ("idea", "running", "done", "dropped")), "")
            sq[m.group(1)] = {"idea": re.sub(r"\*\*", "", cols[0]) if cols else "", "status": status}
    return sq


def main(argv=None) -> None:
    import argparse, subprocess
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", default=str(EXP / "experiments.json"), help="registry file to read")
    ap.add_argument("--tracked-only", action="store_true", help="only include cards tracked by git (for commits)")
    args = ap.parse_args(argv if argv is not None else [])
    registry = {e["id"]: e for e in json.loads(pathlib.Path(args.registry).read_text(encoding="utf-8"))}
    tracked = None
    if args.tracked_only:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "experiments/cards"], capture_output=True, text=True)
        tracked = {pathlib.Path(x).name for x in out.stdout.split()}
    cards = {}
    for p in sorted(CARDS.glob("*.md")):
        if p.name.startswith("_") or (tracked is not None and p.name not in tracked):
            continue
        meta = front_matter(p)
        cards[meta.get("id", p.stem)] = {**meta, "path": p.relative_to(ROOT).as_posix()}
    checks = load_check_results()
    sqs = load_side_quests()

    lines = [
        "# Experiment index",
        "",
        "Generated by `tools/build_experiment_index.py`: **do not edit by hand**; edit the cards/registry instead.",
        "",
        "**Agents: read this before designing a new experiment.** Check whether it was already run, what it found, "
        "and what you can reuse (checkpoints, configs, scripts). Each ID links to its documentation card "
        "(`experiments/cards/<ID>.md`: how to run it, runs, results, artifact paths, how to reuse it, caveats). "
        "\u26a0 = no card yet (AGENTS.md §6 requires one).",
        "",
        "## Experiments (E)",
        "",
        "| ID | Title | Status | Headline result | Reuse | Config / launch |",
        "|---|---|---|---|---|---|",
    ]
    def eid_key(x):
        m = re.search(r"\d+", x)
        return (re.sub(r"\d+", "", x), int(m.group()) if m else 0)

    for eid in sorted(set(registry) | {k for k in cards if k.startswith("E")}, key=eid_key):
        e, c = registry.get(eid, {}), cards.get(eid, {})
        needs_card = bool(e.get("config")) or e.get("status", "planned") != "planned"
        link = (f"[{eid}]({pathlib.Path(c['path']).relative_to('experiments').as_posix()})" if c
                else (f"{eid} \u26a0" if needs_card else f"{eid} (idea)"))
        status = c.get("status") or e.get("status", "")
        headline = c.get("headline") or (e.get("question", "") if status == "planned" else "")
        launch = f"`{e.get('config')}` · `experiments/launch/{eid}.sh`" if e.get("config") else "n/a"
        lines.append(f"| {link} | {cell(c.get('title') or e.get('title'))} | {cell(status)} | {short(headline)} | "
                     f"{short(c.get('reuse', ''))} | {launch} |")

    lines += ["", "## Checks (K) and run side quests", "",
              "| ID | Card | Ran | Verdicts | Result file |", "|---|---|---|---|---|"]
    for cid in sorted(checks, key=eid_key):
        r, c = checks[cid], cards.get(cid, {})
        link = f"[card]({pathlib.Path(c['path']).relative_to('experiments').as_posix()})" if c else "\u26a0"
        lines.append(f"| {cid} | {link} | {r['ran_at']} | {short(r['verdict'], 220)} | `{r['file']}` |")

    done = {k: v for k, v in sqs.items() if v["status"] in ("running", "done", "dropped")}
    lines += ["", "## Side quests that ran (from `experiments/side-quests.md`)", ""]
    if done:
        lines += ["| ID | Idea | Status | Card |", "|---|---|---|---|"]
        for k in sorted(done, key=eid_key):
            c = cards.get(k)
            link = f"[card]({pathlib.Path(c['path']).relative_to('experiments').as_posix()})" if c else "\u26a0"
            lines.append(f"| {k} | {short(done[k]['idea'], 120)} | {done[k]['status']} | {link} |")
    else:
        lines.append("None marked running/done/dropped yet (results of run side quests appear under Checks).")
    n_idea = sum(1 for v in sqs.values() if v["status"] == "idea")
    lines += ["", f"_{n_idea} side-quest ideas not yet run: see `experiments/side-quests.md`. "
              "Claims and their verification status: `experiments/claims.md`._", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(registry)} registry entries, {len(cards)} cards, "
          f"{len(checks)} check results, {len(sqs)} side quests")


if __name__ == "__main__":
    import sys
    main(sys.argv[1:])
